def get_case_by_slug(slug: str):
    """Вернуть кейс по slug или None."""
    for c in CASES:
        if c["slug"] == slug:
            return c
    return None


def get_related_cases(slug: str, limit: int = 3):
    """Вернуть связанные кейсы, отличные от текущего."""
    current = get_case_by_slug(slug)
    related = []
    if current:
        # Сначала кейсы той же категории
        for c in CASES:
            if c["slug"] != slug and c.get("category") == current.get("category"):
                related.append(c)
                if len(related) >= limit:
                    return related
    for c in CASES:
        if c["slug"] != slug and c not in related:
            related.append(c)
            if len(related) >= limit:
                break
    return related

